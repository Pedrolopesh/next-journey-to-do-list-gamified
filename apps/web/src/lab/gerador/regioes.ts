import type { Time } from '../pages/mapas-motor';
import type { Season } from '../pages/mapas-pecas';
import type { BiomeId, LayoutId, Recipe } from './receita';

/**
 * The first journey: 10 regions of 6 maps. Each region is a chapter of the story and each map a
 * stage the character crosses as tasks get done. Six regions are natural places and four are not.
 */

export type Region = {
  id: string;
  name: string;
  /** What this stretch of the journey means for who is doing the tasks. */
  story: string;
  maps: Recipe[];
};

type Row = [
  title: string,
  biome: BiomeId,
  layout: LayoutId,
  time: Time,
  density: number,
  kits: string[],
  about: string,
  /** Season of this map, when it differs from the region's. */
  own?: Season,
];

function region(
  id: string,
  name: string,
  story: string,
  season: Season,
  seed: number,
  rows: Row[],
): Region {
  return {
    id,
    name,
    story,
    maps: rows.map(([title, biome, layout, time, density, kits, about, own], i) => ({
      id: `${id}-${i + 1}`,
      title,
      about,
      biome,
      season: own ?? season,
      layout,
      time,
      density,
      seed: seed + i * 7,
      kits,
      // 4 to 6 screens: the stage loops until it is cleared, so no map is one screen long
      screens: 4 + ((seed + i) % 3),
      // One map in four is under rain (it only shows outdoors, where it does not snow)
      ...((seed / 100 + i) % 4 === 2 ? { weather: 'rain' as const } : {}),
    })),
  };
}

